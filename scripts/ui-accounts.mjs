import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createApplication } from '../server.mjs';

if (!process.env.MANUAL_QA_MODULES) throw new Error('Set MANUAL_QA_MODULES to the Playwright node_modules directory.');
const require = createRequire(join(process.env.MANUAL_QA_MODULES, 'package.json'));
const { chromium } = require('playwright');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
mkdirSync(join(root, 'test-output'), { recursive: true });
const dataDir = mkdtempSync(join(root, 'test-output', 'ui-accounts-'));
const pass = 'UiTestPassword12345';
const app = createApplication({ dataDir, initialAdmin: { username: 'admin', name: 'UI管理者', password: pass } });
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin); await page.locator('#loginId').fill('admin'); await page.locator('#loginPassword').fill(pass);
  await page.locator('#authSubmit').click(); await page.locator('#openTeam').click();
  assert.equal(await page.locator('#roleMatrix tbody tr').count(), 4);
  assert.equal(await page.locator('#newStaffRole option').count(), 4);
  await page.locator('#newStaffName').fill('テスト一般'); await page.locator('#newStaffId').fill('ui-general');
  await page.locator('#newStaffRole').selectOption('viewer'); await page.locator('#addStaffForm button[type=submit]').click();
  await page.locator('#issuedDialog[open]').waitFor();
  const initial = await page.locator('#issuedPassword').inputValue(); assert.match(initial, /^(?=.*[A-Z])(?=.*[a-z])[A-Za-z0-9]{8}$/);
  assert.equal(await page.locator('#issuedPassword').getAttribute('type'), 'password');
  await page.locator('#toggleIssued').click(); assert.equal(await page.locator('#issuedPassword').getAttribute('type'), 'text');
  await page.locator('#closeIssued').click(); assert.equal(await page.locator('#issuedPassword').inputValue(), '');
  const row = page.locator('.staff-row').filter({ has: page.getByLabel('テスト一般のログインID', { exact: true }) });
  await row.getByLabel('テスト一般のログインID', { exact: true }).fill('ui-renamed');
  await row.getByLabel('テスト一般の権限', { exact: true }).selectOption('manager');
  await row.getByRole('button', { name: '変更を保存', exact: true }).click();
  await page.getByText('アカウントを更新しました。変更したスタッフは再ログインしてください。', { exact: true }).waitFor();
  await row.getByRole('button', { name: 'パスワード再設定', exact: true }).click();
  await page.locator('#resetSubmit').click(); await page.locator('#issuedDialog[open]').waitFor();
  const regenerated = await page.locator('#issuedPassword').inputValue(); assert.notEqual(regenerated, initial);
  await page.locator('#closeIssued').click();
  await page.screenshot({ path: join(root, 'test-output/accounts-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Account screen must fit the mobile viewport');
  await page.screenshot({ path: join(root, 'test-output/accounts-mobile.png'), fullPage: true });
  await page.locator('#changePassword').click();
  for (const value of ['Abc1234', 'abcdefgh', 'ABCDEFGH', 'Abcd123!', 'Ａbc12345']) {
    await page.locator('#nextPassword').fill(value);
    assert.equal(await page.locator('#nextPassword').evaluate(input => input.validity.valid), false);
  }
  await page.locator('#nextPassword').fill('Abcd1234');
  assert.equal(await page.locator('#nextPassword').evaluate(input => input.validity.valid), true);
  await page.locator('#nextPassword').fill('');
  await page.screenshot({ path: join(root, 'test-output/password-policy-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: join(root, 'test-output/password-policy-desktop.png'), fullPage: true });
  await page.locator('#closePassword').click();
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const manager = await context.newPage(); manager.on('pageerror', error => errors.push(error.message));
  await manager.goto(origin); await manager.locator('#loginId').fill('ui-renamed'); await manager.locator('#loginPassword').fill(regenerated);
  await manager.locator('#authSubmit').click(); await manager.locator('#sharedBar:not([hidden])').waitFor();
  assert.equal(await manager.locator('#openAdmin').isVisible(), true);
  assert.equal(await manager.locator('#openTeam').isVisible(), false);
  await manager.locator('#openAdmin').click(); assert.equal(await manager.locator('#exportJson').isVisible(), true);
  assert.equal(await manager.locator('#deleteManual').isHidden(), false);
  assert.deepEqual(errors, []);
  console.log('PASS: role matrix, automatic issuance, one-time display cleanup, ID/role changes, password reissue, manager UI and desktop/mobile layout.');
} finally { await browser.close(); await app.close(); }
